void main() {
  //if-else condition, nested condition, switch-case, pattern matching
  ///switch-case
  int mark = 20;

  switch (mark/10) {
    case 10:
      print("A+");
      break;
    case 9:
      print("A+");
      break;
    case 8:
      print("A+");
      break;
    case 7:
      print("B");
      break;
    default:
      print("F");

  }

  ///pattern matching


}
